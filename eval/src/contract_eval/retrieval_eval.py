"""Retrieval metrics against CUAD gold spans.

A retrieved chunk is a hit if its character range overlaps any gold span for
the question. Overlap rather than containment, because ~4.5% of gold spans are
longer than a chunk and can never be fully contained.
"""

from __future__ import annotations

import random
import statistics
from collections.abc import Sequence
from typing import Any

from contract_eval.cuad import GoldSpan


def overlaps(start: int, end: int, span: GoldSpan) -> bool:
    return start < span.end and span.start < end


def first_hit_rank(hits: Sequence[tuple[int, int]], spans: Sequence[GoldSpan]) -> int | None:
    """1-based rank of the first (start, end) range overlapping a gold span, or None."""
    for rank, (start, end) in enumerate(hits, start=1):
        if any(overlaps(start, end, s) for s in spans):
            return rank
    return None


def recall_at(ranks: Sequence[int | None], k: int) -> list[float]:
    return [1.0 if r is not None and r <= k else 0.0 for r in ranks]


def reciprocal_rank_at(ranks: Sequence[int | None], k: int) -> list[float]:
    return [1.0 / r if r is not None and r <= k else 0.0 for r in ranks]


def bootstrap_ci(
    values: Sequence[float], iters: int = 2000, seed: int = 0, alpha: float = 0.05
) -> tuple[float, float]:
    """Percentile bootstrap CI for the mean."""
    rng = random.Random(seed)
    n = len(values)
    means = sorted(statistics.fmean(rng.choices(values, k=n)) for _ in range(iters))
    return means[int(alpha / 2 * iters)], means[int((1 - alpha / 2) * iters) - 1]


def paired_diff_ci(
    a: Sequence[float], b: Sequence[float], iters: int = 2000, seed: int = 0
) -> tuple[float, float, float]:
    """Mean of a-b and its bootstrap CI, resampling questions (paired: same questions for both)."""
    if len(a) != len(b):
        raise ValueError("paired samples must have equal length")
    diffs = [x - y for x, y in zip(a, b, strict=True)]
    lo, hi = bootstrap_ci(diffs, iters=iters, seed=seed)
    return statistics.fmean(diffs), lo, hi


def summarize(ranks: Sequence[int | None]) -> dict[str, float | list[float]]:
    r5 = recall_at(ranks, 5)
    rr = reciprocal_rank_at(ranks, 10)
    return {
        "recall@1": statistics.fmean(recall_at(ranks, 1)),
        "recall@5": statistics.fmean(r5),
        "recall@5_ci": list(bootstrap_ci(r5)),
        "recall@10": statistics.fmean(recall_at(ranks, 10)),
        "mrr@10": statistics.fmean(rr),
        "mrr@10_ci": list(bootstrap_ci(rr)),
    }


def _fmt_ci(ci: Sequence[float]) -> str:
    return f"[{ci[0]:.2f}, {ci[1]:.2f}]"


def render_report(results: dict[str, Any]) -> str:
    """Markdown tables for every run in eval/results/retrieval.json."""
    out = [
        "# Retrieval evaluation",
        "",
        "Generated by `uv run cqa-eval retrieval-report` from `eval/results/retrieval.json`.",
        "A retrieved chunk is a **hit** if its character range overlaps any CUAD gold span for the",
        "question. Retrieval is scoped to the one contract the question is about. 95% CIs are",
        "percentile bootstrap over questions (2,000 resamples); differences are paired.",
        "",
    ]
    for label, run in results.items():
        out += [
            f"## {label}",
            "",
            f"- date: {run['date']}  ",
            f"- command: `{run['command']}`  ",
            f"- database: `{run['database']}`, chunks: {run['chunks']}  ",
            f"- embedding model: `{run['embedding_model']}`  ",
            f"- questions: {run['n']} answerable ({run['question_set']})",
            "",
            "| method | recall@1 | recall@5 (95% CI) | recall@10 | MRR@10 (95% CI) |",
            "|---|---|---|---|---|",
        ]
        for m, s in run["methods"].items():
            out.append(
                f"| {m} | {s['recall@1']:.2f} | {s['recall@5']:.2f} {_fmt_ci(s['recall@5_ci'])} "
                f"| {s['recall@10']:.2f} | {s['mrr@10']:.2f} {_fmt_ci(s['mrr@10_ci'])} |"
            )
        if run["vs_baseline"]:
            base = next(iter(run["vs_baseline"].values()))["baseline"]
            out += [
                "",
                f"Paired difference vs `{base}`:",
                "",
                "| method | Δ recall@5 (95% CI) | Δ MRR@10 (95% CI) |",
                "|---|---|---|",
            ]
            for m, d in run["vs_baseline"].items():
                r, m10 = d["recall@5_diff"], d["mrr@10_diff"]
                out.append(f"| {m} | {r[0]:+.2f} {_fmt_ci(r[1:])} | {m10[0]:+.2f} {_fmt_ci(m10[1:])} |")
        cats = sorted(set(run["categories"]))
        methods = list(run["ranks"])
        out += [
            "",
            "<details><summary>recall@5 by category</summary>",
            "",
            "| category | n | " + " | ".join(methods) + " |",
            "|---|---|" + "---|" * len(methods),
        ]
        for cat in cats:
            idx = [i for i, c in enumerate(run["categories"]) if c == cat]
            cells = []
            for m in methods:
                hits = recall_at([run["ranks"][m][i] for i in idx], 5)
                cells.append(f"{statistics.fmean(hits):.2f}")
            out.append(f"| {cat} | {len(idx)} | " + " | ".join(cells) + " |")
        out += ["", "</details>", ""]
    return "\n".join(out)
